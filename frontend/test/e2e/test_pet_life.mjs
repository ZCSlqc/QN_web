import { test, expect } from '../fixtures/app.mjs'

test('walk keeps its position across styles; petting stops it and shows a real hand', async ({ page, app }) => {
  app.allowedPages = ['/index', '/cat']
  await page.clock.install()
  await page.goto('/cat')
  const room = page.locator('.pet-room')
  await room.scrollIntoViewIfNeeded()
  await expect(page.locator('.cat-frame')).toBeVisible()
  await page.waitForFunction(() => [...document.images].some(i => i.src.includes('pose-0') && i.complete))
  await room.click({ position: { x: 230, y: 490 } })
  await expect(page.locator('.cat-sprite')).toHaveAttribute('data-walking', 'true')
  const before = Number(await page.locator('.cat-wrap').getAttribute('data-x'))
  await page.getByRole('button', { name: '插画', exact: true }).click()
  await expect(page.locator('.cat-frame').last()).toHaveAttribute('src', /illustrated-walk/)
  expect(Number(await page.locator('.cat-wrap').getAttribute('data-x'))).toBeLessThanOrEqual(before)
  await page.locator('.cat-touch').hover()
  await expect(page.locator('.petting-hand')).toBeVisible()
  await page.locator('.cat-touch').click()
  await expect(page.locator('.cat-sprite')).toHaveAttribute('data-walking', 'false')
})

test('sleep shows only head at the home; style and feeding wake-up share the state', async ({ page, app }, testInfo) => {
  app.admin = true; app.petCanFeed = true
  app.allowedPages = ['/index', '/cat']
  await page.clock.install()
  await page.goto('/cat')
  await expect(page.getByRole('button', { name: '休息一下', exact: true })).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.cat-wrap')).toHaveClass(/\bidle\b/)
  await page.locator('.pet-room').scrollIntoViewIfNeeded()
  await page.clock.runFor(100000)
  await expect(page.locator('.sleeping-cat')).toBeVisible({ timeout: 12000 })
  await expect(page.locator('.cat-wrap')).toBeHidden()
  await expect(page.locator('.sleep-zzz')).toHaveText('zzZ')
  await expect(page.locator('.sleeping-cat img')).toHaveAttribute('src', /realistic-sleep/)
  await page.getByRole('button', { name: '插画', exact: true }).click()
  await expect(page.locator('.sleeping-cat img')).toHaveAttribute('src', /illustrated-sleep/)
  await page.screenshot({ path: testInfo.outputPath('sleep-desktop.png') })
  await page.getByRole('button', { name: '画面内投喂猫粮', exact: true }).click()
  await expect(page.locator('.sleeping-cat')).toHaveCount(0)
  await expect(page.locator('.cat-sprite')).toHaveAttribute('data-pose', '3', { timeout: 12000 })
  expect(app.petFeeds).toHaveLength(1)
  await expect(page.locator('.sleep-zzz')).toHaveCount(0)
})

test('mouse runs along the floor; toy changes cancel chasing; mobile sleep fits', async ({ page, app }, testInfo) => {
  app.allowedPages = ['/index', '/cat']
  await page.clock.install()
  await page.goto('/cat')
  await page.getByRole('button', { name: '玩具老鼠', exact: true }).click()
  const mouse = page.locator('.toy-mouse')
  await expect(mouse).toBeVisible()
  await expect(mouse).toHaveCSS('width', '84px')
  await expect(mouse).toHaveCSS('height', '64px')
  await expect(mouse.locator('img')).toHaveCSS('transform', 'none')
  const first = await mouse.evaluate(el => el.style.left)
  await expect.poll(() => mouse.evaluate(el => el.style.left), { timeout: 5000 }).not.toBe(first)
  await expect(mouse.locator('img')).toHaveCSS('transform', 'matrix(-1, 0, 0, 1, 0, 0)')
  await page.getByRole('button', { name: '逗猫棒', exact: true }).click()
  await expect(page.locator('.pet-room')).toHaveCSS('cursor', 'none')
  await expect(page.getByRole('button', { name: '逗猫棒', exact: true })).toHaveCSS('cursor', 'pointer')
  await expect(mouse).toHaveCount(0)
  await expect(page.locator('.toy-teaser img')).toHaveAttribute('src', /hand-teaser.webp/)
  await page.screenshot({ path: testInfo.outputPath('teaser-desktop.png') })
  await page.setViewportSize({ width: 320, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByRole('button', { name: '休息一下', exact: true })).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.cat-wrap')).toHaveClass(/\bidle\b/)
  await page.locator('.pet-room').scrollIntoViewIfNeeded()
  await page.clock.runFor(100000)
  await expect(page.locator('.sleeping-cat')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('sleep-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '轻轻叫醒六一' }).click()
  await expect(page.locator('.cat-wrap')).toBeVisible()
})
