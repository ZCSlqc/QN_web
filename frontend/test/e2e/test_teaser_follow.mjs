import { test, expect } from '../fixtures/app.mjs'

test('desktop pet drag never starts native image dragging; teaser follows and expires', async ({ page, app }) => {
  app.allowedPages = ['/index','/pet']
  await page.clock.install()
  await page.goto('/pet')
  await page.locator('.pet-room').scrollIntoViewIfNeeded()
  await page.waitForFunction(() => document.querySelector('.pet-room').__vueParentComponent.setupState.walk.ready.value.realistic)
  await page.locator('.cat-touch').scrollIntoViewIfNeeded()
  await page.evaluate(() => document.documentElement.style.scrollBehavior = 'auto')
  const cat = await page.locator('.cat-touch').boundingBox()
  expect(await page.evaluate(({x,y}) => !!document.elementFromPoint(x,y)?.closest('.cat-touch'), {x:cat.x+cat.width/2,y:cat.y+cat.height/2})).toBe(true)
  await page.mouse.move(cat.x+cat.width/2,cat.y+cat.height/2)
  await page.mouse.down()
  await page.mouse.move(cat.x+cat.width/2+35,cat.y+cat.height/2+35,{steps:5})
  await expect(page.locator('.petting-hand')).toBeVisible()
  await expect(page.locator('.cat-wrap')).toHaveClass(/pet/)
  const prevented = await page.locator('.cat-frame').last().evaluate(el => !el.dispatchEvent(new DragEvent('dragstart',{bubbles:true,cancelable:true})))
  expect(prevented).toBe(true)
  await page.mouse.up()
  await expect(page.locator('.petting-hand')).toHaveCount(0)
  await page.getByRole('button',{name:'逗猫棒',exact:true}).click()
  const room=await page.locator('.pet-room').boundingBox()
  await page.mouse.move(room.x+room.width*.8,room.y+room.height*.5)
  await expect(page.locator('.cat-sprite')).toHaveAttribute('data-walking','true')
  await page.clock.runFor(1000)
  expect(Number(await page.locator('.cat-wrap').getAttribute('data-x'))).toBeGreaterThan(50)
  await page.mouse.click(room.x+room.width*.2,room.y+room.height*.5)
  await expect(page.locator('.pet-room')).toHaveClass(/is-teasing/)
  expect(await page.evaluate(() => document.querySelector('.pet-room').__vueParentComponent.setupState.walk.facing.value)).toBe(-1)
  await page.locator('.cat-touch').click({position:{x:100,y:100}})
  await expect(page.locator('.pet-room')).toHaveClass(/is-teasing/)
  await page.clock.fastForward(12000)
  await expect(page.locator('.cat-toy')).toHaveCount(0)
  await expect(page.locator('.cat-sprite')).toHaveAttribute('data-walking','false')
})

test.describe('touch',()=>{
  test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  test('taps place teaser without petting; fixed deadline still applies',async({page,app})=>{
    app.allowedPages=['/index','/pet']
    await page.clock.install()
    await page.goto('/pet')
    await page.getByRole('button',{name:'逗猫棒',exact:true}).tap()
    await page.locator('.cat-touch').tap()
    await expect(page.locator('.pet-room')).toHaveClass(/is-teasing/)
    await expect(page.locator('.petting-hand')).toHaveCount(0)
    await page.clock.fastForward(12000)
    await expect(page.locator('.cat-toy')).toHaveCount(0)
    await page.locator('.cat-touch').tap()
    await expect(page.locator('.cat-wrap')).toHaveClass(/pet/)
  })
})
