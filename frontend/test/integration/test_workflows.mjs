test('real backend: login, todo, journey draft, mailbox and share code', async ({ page, browser }) => {
  await page.route('https://tiles.openfreemap.org/**', route => route.abort())
  await page.goto('/login')
  await page.getByRole('textbox', { name: '名字' }).fill('集成测试甲')
  await page.getByRole('textbox', { name: '密码', exact: true }).fill('integration-password')
  await page.getByRole('button', { name: '登 录' }).click()
  await expect(page).toHaveURL(/\/index$/)
  if (await page.evaluate(() => localStorage.getItem('need_blessing') === '1')) await page.getByRole('button', { name: '稍后再说' }).click()
  const token = await page.evaluate(() => localStorage.getItem('token'))
  const headers = { Authorization: `Bearer ${token}` }
  const created = await page.request.post('/api/journeys', { headers, form: { name: JSON.stringify(['上海市', '杭州市']), adcodes: JSON.stringify(['310000', '330100']), departure_date: '2025-04-19', return_date: '2025-04-20', notes: '集成测试旅程' } })
  expect(created.ok()).toBe(true)
  expect((await created.json()).id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
  await page.goto('/journey')
  await page.locator('.journey-record').getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('button', { name: '移除杭州市', exact: true }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.record-place')).toHaveText('上海市、杭州市')
  const after = await (await page.request.get('/api/journeys', { headers })).json()
  expect(after.data[0].name).toEqual(['上海市', '杭州市'])
  await page.request.post('/api/admin/todos', { headers, form: { entry: '共同心愿', type: '旅行', user: '集成测试甲' } })
  await page.goto('/admin')
  await page.getByRole('button', { name: '待办管理' }).click()
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await page.locator('#todo-reflection').fill('完成之后很开心 💪')
  await page.getByRole('button', { name: '完成心愿', exact: true }).click()
  await expect.poll(async () => (await (await page.request.get('/api/table_done_list')).json()).data[0]?.reflection).toBe('完成之后很开心 💪')
  await expect(page.getByText('暂时没有待办心愿')).toBeVisible()
  await page.getByRole('button', { name: '网站设置' }).click()
  await page.locator('#new-share-code').fill('changed-integration-code')
  await page.getByRole('button', { name: '保存分享码' }).click()
  await page.locator('.el-message-box').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('分享码已保存并立即生效')).toBeVisible()
  expect((await (await page.request.post('/api/register_process', { form: { username: '新访客', userpwd: 'visitor-password', checkcode: 'integration-share-code' } })).json()).flag).toBe(-3)
  expect((await (await page.request.post('/api/register_process', { form: { username: '新访客', userpwd: 'visitor-password', checkcode: 'changed-integration-code' } })).json()).flag).toBe(1)
  await page.goto('/index')
  await page.locator('.mailbox-trigger').click()
  await page.getByRole('button', { name: '写封信', exact: true }).click()
  await page.locator('#mail-title').fill('真实接口测试')
  await page.locator('#mail-body').fill('仅存在于测试数据库的一封信。')
  await page.getByRole('button', { name: '寄给ta', exact: true }).click()
  await expect(page.locator('.mailbox-panel')).toBeHidden()
  await page.locator('.mailbox-trigger').click()
  await page.locator('.letter-item').filter({ hasText: '真实接口测试' }).click()
  await expect(page.locator('.letter-paper')).toContainText('真实接口测试')
  const webOrigin = new URL(page.url()).origin
  const peer = await browser.newContext()
  try {
    const login = await peer.request.post(`${webOrigin}/api/login_process`, { form: { username: '集成测试乙', userpwd: 'integration-password' } })
    const peerToken = (await login.json()).token
    await peer.addInitScript(value => localStorage.setItem('token', value), peerToken)
    const reader = await peer.newPage()
    await reader.goto(`${webOrigin}/index`)
    await expect(reader.locator('.mailbox-badge')).toHaveText('1')
    await reader.locator('.mailbox-trigger').click()
    await reader.locator('.letter-item').click()
    await expect(reader.locator('.mailbox-badge')).toHaveCount(0)
    await reader.locator('#mail-comment').fill('收到啦')
    await reader.getByRole('button', { name: '留下回应' }).click()
    await expect(reader.locator('.mail-comment')).toContainText('收到啦')
    await page.getByRole('button', { name: '刷新留言' }).click()
    await expect(page.locator('.mail-comment')).toContainText('收到啦')
    await expect(page.locator('.letter-receipt')).toContainText('对方已读')
  } finally { await peer.close() }
  await page.getByRole('button', { name: '关闭信箱', exact: true }).click()
  await page.getByRole('button', { name: '账号', exact: true }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/me', { headers })).status()).toBe(401)
})

test('real backend: pet food is persisted and the same feed cannot be charged twice', async ({ page }) => {
  const login = await page.request.post('/api/login_process', { form: { username: '集成测试甲', userpwd: 'integration-password' } })
  const token = (await login.json()).token
  await page.addInitScript(value => localStorage.setItem('token', value), token)
  const headers = { Authorization: `Bearer ${token}` }
  await page.request.post('/api/photos', { headers, multipart: { file: { name: 'pet-test.webp', mimeType: 'image/webp', buffer: readFileSync(fileURLToPath(new URL('../../public/optimized/album/college (1).webp', import.meta.url))) } } })
  await page.goto('/cat')
  const before = (await (await page.request.get('/api/pet', { headers })).json()).inventory.treat
  await page.getByRole('button', { name: '投喂猫条', exact: true }).click()
  await expect.poll(async () => (await (await page.request.get('/api/pet', { headers })).json()).inventory.treat).toBe(before - 1)
  await expect(page.locator('.diary-list')).toContainText('集成测试甲')
  await page.reload()
  await expect(page.getByRole('button', { name: '投喂猫条', exact: true })).toContainText(String(before - 1))
  const cansBefore = (await (await page.request.get('/api/pet', { headers })).json()).inventory.can
  const body = { food: 'can', request_key: 'integration-pet-retry-key' }
  const one = await page.request.post('/api/pet/feed', { headers, form: body })
  const two = await page.request.post('/api/pet/feed', { headers, form: body })
  expect((await one.json()).event_id).toBe((await two.json()).event_id)
  const state = await (await page.request.get('/api/pet', { headers })).json()
  expect(state.inventory.can).toBe(cansBefore - 1)
})
